// 学习目标：
//   1. 掌握函数定义、参数与返回值的写法。
//   2. 理解 Rust"表达式 vs 语句"的区分（核心！）。
//   3. 理解作用域 {} 如何控制变量生命周期。
// 前置知识：第 01、02 课。
// 本课覆盖：fn / 参数类型标注 / 表达式返回 / 块表达式 / 作用域。
// 运行方式：
//   rustc 03_functions_and_scope.rs && ./03_functions_and_scope
// ============================================================

fn main() {
    // ------------------------------------------------------------
    // 1. 调用函数
    //    Rust 函数命名约定：snake_case。
    // ------------------------------------------------------------
    greet("Rust");
    let sum = add(3, 4);
    println!("3 + 4 = {sum}");

    // ------------------------------------------------------------
    // 2. 语句 (Statement) vs 表达式 (Expression)
    //    - 语句：执行操作，"不"返回值。以 ; 结尾。例：let x = 5;
    //    - 表达式：执行并返回一个值。例：5 + 3、{ ... }、if ... else ...
    //    - 区别口诀：加了分号变语句（返回 ()），不加分号是表达式。
    // ------------------------------------------------------------

    // 块表达式：{} 整体就是一个表达式，最后一行不带分号即为返回值。
    let doubled = {
        let value = 10;
        value * 2 // 注意：没有分号 → 这是返回值
    };
    println!("块表达式 doubled = {doubled}");

    // 反例：加分号会让块返回 ()
    #[allow(clippy::let_unit_value, unused_must_use)]
    let nothing = {
        let v = 10;
        let _ = v * 2; // 加了分号，块的返回值变成 ()；用 let _ 避免 lint 噪音
    };
    println!("nothing 是 unit 值：{:?}", nothing);

    // ------------------------------------------------------------
    // 3. 作用域：{} 控制变量"何时出生、何时死亡"。
    //    出了作用域，变量被自动 drop（释放资源）——这是 RAII。
    // ------------------------------------------------------------
    {
        let inner = String::from("只在这个作用域中存在");
        println!("{inner}");
    } // <-- inner 在这里被自动 drop，String 的堆内存被释放。
    // println!("{inner}"); // 编译错误：inner 已经不在作用域中。

    // ------------------------------------------------------------
    // 4. 提前返回 vs 表达式返回
    //    Rust 推荐"最后一个表达式作为返回值"的写法，
    //    需要中途返回时才用 return；用 return 时要加分号。
    // ------------------------------------------------------------
    println!("abs(-7) = {}", abs(-7));
    println!("clamp(15, 0, 10) = {}", clamp(15, 0, 10));

    // ------------------------------------------------------------
    // 5. 无返回值的函数：返回 () (unit)
    //    不写 -> 等价于 -> ()
    // ------------------------------------------------------------
    let r = log_msg("hello");
    println!("log_msg 返回值 = {:?}", r);
}

// ----- 函数定义示例 -----

// 参数必须显式标注类型——Rust 函数签名是"契约"。
fn greet(name: &str) {
    println!("你好，{name}!");
}

// -> 后面是返回类型；函数体最后表达式即返回值。
fn add(left: i32, right: i32) -> i32 {
    left + right // 没有分号
}

// 提前 return 的写法：
fn abs(n: i32) -> i32 {
    if n < 0 {
        return -n; // 中途返回需要分号
    }
    n // 最后一行不带分号
}

// 多个 if 分支也是表达式：
fn clamp(value: i32, low: i32, high: i32) -> i32 {
    if value < low {
        low
    } else if value > high {
        high
    } else {
        value
    }
}

// 无返回值时返回类型可省略：
fn log_msg(msg: &str) {
    println!("[LOG] {msg}");
}

// ============================================================
// 本课小结
//   - 函数签名必须有完整类型标注；函数体最后一个表达式是返回值。
//   - "加分号变语句"是 Rust 最容易踩的语法坑。
//   - {} 控制作用域，离开作用域变量自动 drop（RAII）。
//
// 常见陷阱
//   - 函数最后一行不小心加了分号，编译报错 "expected i32, found ()"。
//   - 在 if 分支里某分支加分号、另一分支没加 → 类型不一致。
//   - 用 return 不加分号 → 编译报错。
//
// 最佳实践
//   - 简短函数（< 5 行）尽量用"最后表达式"返回，避免 return。
//   - 函数职责单一，参数 ≤ 4 个；更多用 struct 包装（见第 07 课）。
//   - 命名遵循 snake_case；私有函数不加 pub。
//
