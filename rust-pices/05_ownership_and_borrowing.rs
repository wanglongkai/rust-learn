// ============================================================
// 第 05 课：所有权与借用 (Ownership & Borrowing) —— Rust 的灵魂
// ------------------------------------------------------------
// 学习目标：
//   1. 理解 Rust 为什么不需要 GC：所有权 + 编译期检查。
//   2. 掌握三条所有权规则。
//   3. 理解 move、clone、Copy 的区别。
//   4. 理解"借用 (&T / &mut T)"的基本概念（细节留到第 06 课）。
// 前置知识：第 01~04 课。
// 本课覆盖：ownership / move / clone / Copy / drop / 借用基础。
// 运行方式：
//   rustc 05_ownership_and_borrowing.rs && ./05_ownership_and_borrowing
// ============================================================
//
// === Rust 所有权三定律（背下来）===
//   1. 每一个值都有一个"所有者 (owner)"变量。
//   2. 任意时刻，一个值"有且仅有"一个所有者。
//   3. 当所有者离开作用域，这个值会被自动 drop（资源释放）。
//
// 这套规则在编译期检查，让 Rust 既不要 GC，也不会内存泄漏 / 悬垂指针。

fn main() {
    // ------------------------------------------------------------
    // 1. move：把所有权"移交"出去
    //    String 在堆上分配内存。把 s1 赋值给 s2 时，
    //    Rust 不复制堆数据（避免开销），而是把"所有权"从 s1 移交给 s2。
    //    从这一刻起，s1 就失效了。
    // ------------------------------------------------------------
    let s1 = String::from("hello");
    let s2 = s1; // <-- move 发生在这里
    // println!("{s1}"); // 编译错误: borrow of moved value: `s1`
    println!("move 之后 s2 = {s2}");

    // ------------------------------------------------------------
    // 2. clone：显式深拷贝
    //    如果你确实想要两份独立的数据，用 .clone()。
    //    .clone() 通常意味着"开销" → 看到 clone 就停下来想想是否必要。
    // ------------------------------------------------------------
    let a = String::from("rust");
    let b = a.clone(); // 深拷贝，a、b 各拥有一份独立堆数据
    println!("a = {a}, b = {b}");

    // ------------------------------------------------------------
    // 3. Copy trait：栈上数据，复制即"按位拷贝"，不 move
    //    所有整数、浮点、bool、char、以及"全部成员都 Copy 的元组/数组"
    //    都实现了 Copy。赋值等于复制，原变量仍然可用。
    // ------------------------------------------------------------
    let x = 5;
    let y = x;
    println!("Copy 类型：x = {x}, y = {y}（x 仍然可用）");

    let t1: (i32, bool) = (1, true);
    let t2 = t1;            // t1 是 Copy，所以 t1 还在
    println!("t1 = {:?}, t2 = {:?}", t1, t2);

    let t3 = (1, String::from("hi"));
    let _t4 = t3;
    // println!("{:?}", t3); // 错：含 String → 整个元组不再 Copy

    // ------------------------------------------------------------
    // 4. 函数传参也会 move（或 copy）
    //    把变量传给函数，所有权要么被 move 进去，要么被 Copy。
    // ------------------------------------------------------------
    let s = String::from("ownership");
    take_ownership(s);
    // println!("{s}"); // 错：s 已经被 move 进函数

    let n = 10;
    take_copy(n);
    println!("n 仍然可用 = {n}"); // 因为 i32 是 Copy

    // ------------------------------------------------------------
    // 5. 解决方案：用"借用 (&)"避免移交所有权
    //    把引用传给函数，所有权还留在调用方。
    //    引用又分两种：
    //      &T     不可变引用（共享借用）：可以同时存在多个。
    //      &mut T 可变引用（独占借用）：同一作用域只能有一个，并且和不可变借用互斥。
    //    详细的规则下一课讲，这里先体感。
    // ------------------------------------------------------------
    let text = String::from("hello rust");
    let len = calculate_length(&text); // 借用，不转移所有权
    println!("'{text}' 的长度是 {len}");

    let mut msg = String::from("hello");
    append_world(&mut msg);            // 可变借用，函数可以修改原值
    println!("修改后 msg = {msg}");

    // ------------------------------------------------------------
    // 6. 离开作用域 → 自动 drop
    //    Rust 编译器自动在作用域末尾插入 drop 调用，
    //    所以你永远不需要手动 free / delete。
    // ------------------------------------------------------------
    {
        let owned = String::from("我会在花括号结束时被释放");
        println!("{owned}");
    } // <-- 这里 String 的堆内存被释放
    println!("已经出了作用域");
}

fn take_ownership(s: String) {
    println!("函数拿到了所有权: {s}");
} // s 在这里被 drop

fn take_copy(n: i32) {
    println!("函数拿到了一份 copy: {n}");
}

fn calculate_length(s: &String) -> usize {
    // s 是不可变引用，只能读不能改。
    s.len()
} // s 离开作用域，但因为它不拥有数据，所以什么也没发生。

fn append_world(s: &mut String) {
    s.push_str(", World"); // 通过可变引用修改原数据
}

// ============================================================
// 本课小结
//   - 所有权三定律是 Rust 安全性的基石，必须背熟。
//   - 赋值 / 传参，对 Copy 类型是复制，对非 Copy 类型是 move。
//   - 不想 move 又不想 clone？用借用 (&、&mut)。
//
// 常见陷阱
//   - move 后还想用原变量 → 编译错误 "borrow of moved value"。
//   - 看见 String 就 .clone() → 性能差，多数时候用 & 借用更好。
//   - 误以为整个 struct 是 Copy → 只要包含 String/Vec 这种堆类型就不是 Copy。
//
// 最佳实践
//   - 函数参数优先用 & / &mut；只有真的需要"接管"时才接收 T。
//   - 看到 .clone() 先暂停：是不是用引用就能解决？
//   - 公开 API 的参数尽量"宽"（接 &str 而非 &String，接 &[T] 而非 &Vec<T>）。
