// ============================================================
// 第 04 课：控制流 (Control Flow)
// ------------------------------------------------------------
// 学习目标：
//   1. 掌握 if / else 的表达式用法。
//   2. 掌握 loop / while / for 三种循环。
//   3. 学会用 break value 让循环返回值，用 'label 控制嵌套循环。
//   4. 掌握范围 a..b 与 a..=b。
// 前置知识：第 03 课表达式概念。
// 本课覆盖：if-else / loop / while / for / range / break-label。
// 运行方式：
//   rustc 04_control_flow.rs && ./04_control_flow
// ============================================================

fn main() {
    // ------------------------------------------------------------
    // 1. if 是表达式 → 可以用来给变量赋值。
    //    所有分支返回类型必须一致；条件必须是 bool（Rust 不会把数字隐式当真假！）。
    // ------------------------------------------------------------
    let number = 7;
    let size = if number < 5 { "small" } else { "large" };
    println!("{number} is {size}");

    // 多分支：
    let kind = if number % 15 == 0 {
        "FizzBuzz"
    } else if number % 3 == 0 {
        "Fizz"
    } else if number % 5 == 0 {
        "Buzz"
    } else {
        "number"
    };
    println!("{number} -> {kind}");

    // 错误示例（不要写）：
    // if 1 { ... }                 // 错：必须是 bool
    // let x = if c { 1 } else { "1" }; // 错：分支类型不一致

    // ------------------------------------------------------------
    // 2. loop：无条件无限循环，用 break 跳出。
    //    特别之处：break 可以"返回值"，让 loop 整体作为表达式有值。
    // ------------------------------------------------------------
    let mut counter = 0;
    let result = loop {
        counter += 1;
        if counter == 3 {
            break counter * 10; // <-- 把这个值作为 loop 的"结果"
        }
    };
    println!("loop 返回值 = {result}");

    // ------------------------------------------------------------
    // 3. while：条件为真时循环。
    //    适合"循环次数不确定"的场景。
    // ------------------------------------------------------------
    let mut n = 3;
    while n > 0 {
        println!("while: {n}");
        n -= 1;
    }

    // ------------------------------------------------------------
    // 4. for：遍历"任何能产生 Iterator 的东西"——这是 Rust 用得最多的循环。
    //    几乎所有集合（数组、Vec、HashMap）和范围都能 for 遍历。
    // ------------------------------------------------------------
    let items = ["a", "b", "c"];
    for item in items {
        println!("for item = {item}");
    }

    // 想拿索引时用 .enumerate()
    for (idx, item) in items.iter().enumerate() {
        println!("idx={idx}, item={item}");
    }

    // ------------------------------------------------------------
    // 5. 范围 (Range)：a..b 半开 [a, b)；a..=b 闭区间 [a, b]。
    //    .rev() 可以反向。
    // ------------------------------------------------------------
    for i in 0..3 {
        println!("0..3 -> {i}"); // 0,1,2
    }
    for i in 1..=3 {
        println!("1..=3 -> {i}"); // 1,2,3
    }
    for i in (1..=3).rev() {
        println!("反向 -> {i}"); // 3,2,1
    }

    // ------------------------------------------------------------
    // 6. 嵌套循环 + 标签 'label
    //    给循环命名后，可以让 break / continue 精确控制到哪一层。
    // ------------------------------------------------------------
    let mut found = (0, 0);
    'outer: for i in 0..5 {
        for j in 0..5 {
            if i * j > 6 {
                found = (i, j);
                break 'outer; // 直接跳出外层
            }
        }
    }
    println!("找到第一个 i*j > 6 的位置: {:?}", found);
}

// ============================================================
// 本课小结
//   - if 是表达式：分支类型必须一致；条件必须是 bool。
//   - loop 最强大：可以 break 返回值；适合"我自己控制何时退出"。
//   - while 适合条件循环；for 适合遍历集合/范围。
//   - 用 'label 处理多层嵌套，比 flag 变量优雅。
//
// 常见陷阱
//   - if 不同分支返回不同类型，比如一个返回 () 一个返回 i32。
//   - for 一边遍历集合一边修改集合大小 → 借用检查器会拦下来。
//   - while 条件忘记变化 → 死循环。
//
// 最佳实践
//   - 优先 for，其次 while，最后 loop。
//   - 遍历集合用 for ... in &collection / &mut collection，根据是否要改变内容选。
//   - "查找型循环"可以考虑迭代器方法：.find()、.position()，比手写循环更地道。
//
