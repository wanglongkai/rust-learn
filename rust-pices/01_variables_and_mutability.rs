// ============================================================
// 第 01 课：变量与可变性 (Variables & Mutability)
// ------------------------------------------------------------
// 学习目标：
//   1. 理解 Rust 默认"不可变"的设计哲学。
//   2. 掌握 let / mut / const 三种声明方式的区别。
//   3. 理解 shadowing（变量遮蔽）与 mut 的本质区别。
// 前置知识：无（这是第一课）。
// 本课覆盖：let、mut、const、shadowing。
// 运行方式：
//   rustc 01_variables_and_mutability.rs && ./01_variables_and_mutability
// ============================================================

fn main() {
    // ------------------------------------------------------------
    // 1. 默认不可变：let 声明的变量一旦绑定，不能再改。
    //    这是 Rust 安全性的基础设计——防止"意外修改"导致 bug。
    // ------------------------------------------------------------
    let x = 5;
    println!("不可变变量 x = {x}");
    // x = 6; // 编译错误：cannot assign twice to immutable variable

    // ------------------------------------------------------------
    // 2. 用 mut 显式声明"我就是要改"。
    //    显式性是 Rust 的核心哲学：能改的东西必须看得见。
    // ------------------------------------------------------------
    let mut count = 0;
    count += 1;
    count += 1;
    println!("可变变量 count = {count}");

    // ------------------------------------------------------------
    // 3. const：编译期常量。
    //    - 必须显式标注类型。
    //    - 只能绑定到编译期可求值的表达式（不能调用普通函数）。
    //    - 命名约定 SCREAMING_SNAKE_CASE。
    //    - 可以放在任何作用域（包括全局）。
    // ------------------------------------------------------------
    const MAX_POINTS: u32 = 100_000;
    const SECONDS_PER_HOUR: u32 = 60 * 60; // 编译期算好
    println!("常量 MAX_POINTS = {MAX_POINTS}, SECONDS_PER_HOUR = {SECONDS_PER_HOUR}");

    // ------------------------------------------------------------
    // 4. shadowing（遮蔽）：用 let 重新声明同名变量。
    //    它不是"修改"，而是"创建一个新绑定，把旧的盖住"。
    //    关键点：可以改变类型！这是 mut 做不到的。
    // ------------------------------------------------------------
    let spaces = "   ";           // 此时 spaces 是 &str
    let spaces = spaces.len();    // 现在 spaces 是 usize（类型变了！）
    println!("空格数量 spaces = {spaces}");

    let score = 10;
    let score = score + 5;        // 还是 i32
    let score = format!("{score} 分"); // 变成 String
    println!("shadowing 后的 score = {score}");

    // ------------------------------------------------------------
    // 5. mut vs shadowing 对比（核心区别）
    //    - mut: 同一个绑定，值可改，但类型不能变。
    //    - shadowing: 创建新绑定，可以彻底改变类型，旧值在新作用域结束前其实还活着（但被遮住了）。
    // ------------------------------------------------------------
    let mut number = 5;
    println!("number 初值 = {number}");
    number = 10;        // OK
    // number = "ten";  // 编译错误：mut 不能改类型

    let demo = "5";
    let demo: i32 = demo.parse().expect("不是数字"); // shadowing 改类型，常用！
    println!("number = {number}, demo = {demo}");
}

// ============================================================
// 本课小结
//   - 默认不可变 + 显式 mut，让"会变化的状态"在代码里一目了然。
//   - const 是编译期常量；let 是运行期绑定。
//   - shadowing 不是修改，是"新建并覆盖"，且能改类型。
//
// 常见陷阱
//   - 想"改类型"时用了 mut → 编译错误，应该用 shadowing。
//   - 想"全局常量"用了 let → let 不能在模块顶层使用，要用 const 或 static。
//   - 把 const 当成"全大写的 let"乱用 → const 不能调用任意函数。
//
// 最佳实践
//   - 优先保持不可变；只有真的需要修改才加 mut。
//   - 类型转换/逐步精炼数据时优先用 shadowing，而不是引入新名字 (s, s1, s2...)。
//   - 全大写命名仅留给 const / static。
