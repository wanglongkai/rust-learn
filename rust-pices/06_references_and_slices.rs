// 第 06 课：引用与切片 (References & Slices)
// ------------------------------------------------------------
// 学习目标：
//   1. 掌握 & 和 &mut 的使用规则（借用检查器三条铁律）。
//   2. 理解切片 (slice) 是"不拥有数据的引用视图"。
//   3. 学会用 &str 和 &[T] 写出更通用的 API。
// 前置知识：第 05 课所有权。
// 本课覆盖：&T / &mut T / 解引用 * / &str / &[T]。
// 运行方式：
//   rustc 06_references_and_slices.rs && ./06_references_and_slices
// ============================================================
//
// === 借用检查器三条铁律 ===
//   1. 任意时刻，要么有"任意多个不可变引用"，要么有"恰好一个可变引用"。
//      不能同时有可变和不可变引用。
//   2. 引用必须始终有效（编译器靠生命周期保证，第 14 课展开）。
//   3. 引用永远不为 null（用 Option<&T> 表达"也许没有"）。
//
// 一句话总结：共享不可变，可变不共享。

fn main() {
    // ------------------------------------------------------------
    // 1. 不可变引用 &T：同一时间可以有多个，都只能读。
    // ------------------------------------------------------------
    let value = 10;
    let r1 = &value;
    let r2 = &value;
    let r3 = &value;
    println!("r1={r1}, r2={r2}, r3={r3} (可以同时存在很多个)");

    // ------------------------------------------------------------
    // 2. 可变引用 &mut T：同一时间只能有一个，且和不可变引用互斥。
    //    这条规则在编译期消除了"数据竞争 (data race)"——多线程安全的核心保证。
    // ------------------------------------------------------------
    let mut counter = 0;
    let m1 = &mut counter;
    *m1 += 5; // 解引用 * 才能修改它指向的值
    // let m2 = &mut counter; // 错：已经有一个 &mut 了
    // let r  = &counter;     // 错：&mut 活着时不能再 & 借
    println!("counter = {}", counter); // m1 已经不再使用，这里可以读

    // ------------------------------------------------------------
    // 3. "非词法生命周期 (NLL)"：引用的活跃范围由"最后一次使用"决定，
    //    不是花括号。这让借用检查更宽松、更智能。
    // ------------------------------------------------------------
    let mut data = vec![1, 2, 3];
    let r = &data;                  // 不可变借用开始
    println!("不可变读：{:?}", r);  // 最后一次使用 r —— 借用结束
    data.push(4);                   // 现在可以可变操作了
    println!("修改后：{:?}", data);

    // ------------------------------------------------------------
    // 4. 字符串切片 &str：对 String 一部分的"借用视图"
    //    - 不拥有数据，不需要释放。
    //    - 字面量 "hello" 的类型就是 &'static str（指向只读段）。
    //    - 索引必须落在 UTF-8 字符边界上，否则 panic。
    // ------------------------------------------------------------
    let sentence = String::from("hello rust world");
    let hello: &str = &sentence[0..5];
    let rust:  &str = &sentence[6..10];
    let world: &str = &sentence[11..];
    println!("切片: '{hello}' / '{rust}' / '{world}'");

    // 在函数签名里接收 &str 比 &String 更通用，下面展示。
    let first = first_word(&sentence);
    println!("第一个单词: {first}");
    let first = first_word("inline string"); // 字面量也能传
    println!("第一个单词: {first}");

    // ------------------------------------------------------------
    // 5. 数组切片 &[T]：和 &str 同理，是对数组/Vec 的"借用视图"
    //    用 &[T] 写函数，比 &Vec<T> 通用得多。
    // ------------------------------------------------------------
    let numbers = [10, 20, 30, 40, 50];
    let middle: &[i32] = &numbers[1..4];
    println!("数组切片 = {:?}, 长度 = {}", middle, middle.len());
    println!("sum = {}", sum(middle));
    println!("sum = {}", sum(&numbers));       // 数组可隐式转切片
    println!("sum = {}", sum(&vec![1, 2, 3])); // Vec 也行

    // ------------------------------------------------------------
    // 6. 悬垂引用 (dangling reference)：Rust 用编译期拒绝这种 bug
    //    下面被注释掉的函数无法编译，因为返回的引用指向已释放的栈数据。
    // ------------------------------------------------------------
    // fn dangle() -> &String {
    //     let s = String::from("oops");
    //     &s
    // } // s 在这里被 drop，引用就悬垂了 → 编译器拒绝
}

// 经典案例：找出字符串中第一个空格之前的部分。
// 接受 &str 而非 &String，调用方更灵活。
fn first_word(s: &str) -> &str {
    let bytes = s.as_bytes();
    for (i, &b) in bytes.iter().enumerate() {
        if b == b' ' {
            return &s[..i];
        }
    }
    s
}

// 接受 &[i32] 让函数同时支持数组、Vec、切片。
fn sum(values: &[i32]) -> i32 {
    let mut total = 0;
    for v in values {
        total += v;
    }
    total
}

// ============================================================
// 本课小结
//   - 借用检查器铁律：共享不可变 / 可变不共享，编译期消除数据竞争。
//   - NLL：借用活到"最后一次使用"，不是花括号结束。
//   - &str 和 &[T] 是"借用视图"，写 API 时优先使用，更通用。
//
// 常见陷阱
//   - 同时拿 &mut 和 & → 编译错误"cannot borrow as ...whilst..."。
//   - 在循环里 &mut 又 push/扩容 → 借用冲突。
//   - 字符串切片越过 UTF-8 边界（如中文 1 字节切片）→ 运行时 panic。
//
// 最佳实践
//   - 参数类型选择口诀：
//       只读   → &str / &[T] / &T
//       要改   → &mut T
//       要存   → T (拿走所有权)
//   - 不要用 &String / &Vec<T>，几乎总是可以用 &str / &[T] 替代。
//   - 把"读取借用"尽快用完，让出空间给后续的可变借用（依赖 NLL）。
