// ============================================================
// 第 02 课：数据类型 (Scalar & Compound)
// ------------------------------------------------------------
// 学习目标：
//   1. 掌握 Rust 的 4 类标量类型：整数、浮点数、布尔、字符。
//   2. 掌握 2 类复合类型：元组、数组。
//   3. 理解"静态类型 + 类型推导"的工作方式。
// 前置知识：第 01 课 let / mut。
// 本课覆盖：i32 / u8 / f64 / bool / char / tuple / array。
// 运行方式：
//   rustc 02_data_types_scalar_and_compound.rs && ./02_data_types_scalar_and_compound
// ============================================================

fn main() {
    // ------------------------------------------------------------
    // 1. 标量类型 (Scalar Types)
    //    - 整数：i8/i16/i32/i64/i128 + 无符号 u 系列 + isize/usize（指针大小）。
    //    - 浮点：f32 / f64（默认 f64）。
    //    - 布尔：bool，只有 true / false。
    //    - 字符：char，4 字节 Unicode 标量值（注意：不是 1 字节！）。
    // ------------------------------------------------------------
    let age: u8 = 30;                 // 0 ~ 255 之间
    let temperature: f64 = 36.6;      // 双精度浮点
    let is_active: bool = true;
    let heart: char = '爱';           // 中文也是单个 char
    println!(
        "age={age}, temperature={temperature}, is_active={is_active}, heart={heart}"
    );

    // ------------------------------------------------------------
    // 2. 整数字面量的多种写法 + 可读性分隔符 _
    //    分隔符 _ 是给人看的，编译器会忽略。
    // ------------------------------------------------------------
    let decimal = 98_222;       // 十进制
    let hex = 0xff;             // 十六进制
    let octal = 0o77;           // 八进制
    let binary = 0b1111_0000;   // 二进制
    let byte = b'A';            // u8 字面量，只能用 ASCII
    println!("decimal={decimal}, hex={hex}, octal={octal}, binary={binary}, byte={byte}");

    // ------------------------------------------------------------
    // 3. 数值类型转换：必须用 as，没有隐式转换！
    //    这是 Rust 的安全性：禁止编译器替你"偷偷"丢失精度。
    // ------------------------------------------------------------
    let a: i32 = 1000;
    let b: i64 = a as i64;
    let c: u8 = a as u8; // 1000 超出 u8(0~255)，会被"截断"为 232，as 不会报错，要小心
    println!("a={a}, b={b}, c={c} (注意：c 是截断后的结果)");

    // ------------------------------------------------------------
    // 4. 元组 (Tuple)：固定长度，类型可以不同。
    //    适合临时打包一组关联值，比如函数返回多个值。
    // ------------------------------------------------------------
    let user: (&str, u32, bool) = ("Alice", 18, true);
    // 解构（destructuring）：一次性把元素绑到名字。
    let (name, level, enabled) = user;
    println!("name={name}, level={level}, enabled={enabled}");
    // 也能用 .index 访问。
    println!("user.0 = {}, user.1 = {}", user.0, user.1);

    // 空元组 () 叫 "unit"，是没有返回值的函数的"返回类型"。
    let unit: () = ();
    println!("unit value = {:?}", unit);

    // ------------------------------------------------------------
    // 5. 数组 (Array)：固定长度，所有元素同类型。
    //    长度是类型的一部分：[i32; 5] 和 [i32; 4] 是不同类型！
    //    适合"编译期已知长度、栈上数据"。需要可变长度时用 Vec（第 09 课）。
    // ------------------------------------------------------------
    let numbers: [i32; 5] = [1, 2, 3, 4, 5];
    println!("第一个数字 = {}, 数组长度 = {}", numbers[0], numbers.len());

    // [初始值; 长度] 简写：常用来快速初始化
    let zeroes = [0; 3];
    println!("zeroes = {:?}", zeroes);

    // 数组越界访问：编译期或运行时 panic，绝不会读到非法内存。
    // let _ = numbers[10]; // 运行时 panic: index out of bounds

    // ------------------------------------------------------------
    // 6. 类型推导：写不写类型？
    //    - 局部变量、能从右值推出来的，省略。
    //    - 函数签名、struct 字段、常量，必须写。
    // ------------------------------------------------------------
    let inferred = 42;          // i32（默认整数类型）
    let inferred_f = 3.14;      // f64（默认浮点）
    let explicit: u64 = 42;     // 想要 u64 时必须显式标注
    println!("inferred={inferred}, inferred_f={inferred_f}, explicit={explicit}");
}

// ============================================================
// 本课小结
//   - 标量：i/u 系列、f32/f64、bool、char（4 字节 Unicode）。
//   - 元组适合"少量、临时、异构"打包；数组适合"等长、同类型"。
//   - 没有隐式类型转换，必须 as；as 不检查溢出，需谨慎。
//
// 常见陷阱
//   - 把 char 当 1 字节用：char 是 4 字节 Unicode。
//   - 用 i32 装毫秒时间戳：很快溢出，用 i64 / u64。
//   - 用数组当动态列表：数组长度是类型的一部分，不能扩容，要用 Vec。
//
// 最佳实践
//   - 默认 i32 + f64 + usize（索引/长度）。
//   - 业务 ID 用 newtype 包裹（见 BEST_PRACTICES.md），不要满世界传 u64。
//   - 不确定数据长度 → 用 Vec<T>，不要硬塞数组。
//
